INSERT INTO receita.nicho_cnaes (nicho, cnae, rotulo)
SELECT n.nicho, n.cnae, c.descricao
  FROM novos_nichos n JOIN receita.cnaes c ON c.codigo = n.cnae
ON CONFLICT DO NOTHING;

-- Conferir: atividades que não existem na Receita (devem ser poucas ou nenhuma)
SELECT n.nicho, n.cnae AS cnae_nao_encontrado
  FROM novos_nichos n LEFT JOIN receita.cnaes c ON c.codigo = n.cnae
 WHERE c.codigo IS NULL ORDER BY 1, 2;

-- Conferir: cada nicho novo com as atividades gravadas
SELECT n.nicho, string_agg(n.cnae || ' ' || coalesce(c.descricao, '?'), ' | ' ORDER BY n.cnae) AS atividades
  FROM novos_nichos n LEFT JOIN receita.cnaes c ON c.codigo = n.cnae
 GROUP BY n.nicho ORDER BY n.nicho;
